#' Get data from a SQLite-database
#'
#' This function can be used to obtain data from a local or remote SQLite
#' database. If the full path with filename is provided in `SQLiteDB`, it will
#' look for that SQLite-file locally. If `SQLiteDB` is `NULL` it will establish
#' a connection with a remote server. There is also functionality to use an
#' existing opened data base connection that can be provided in
#' `use_connection`. For instance, when creating residence patches within a
#' loop of tags and tide ID's. Because establishing a connection within a
#' for-loop takes a long time, an established connection can be used.
#' @author Pratik R. Gupte & Allert I. Bijleveld & Johannes Krietsch
#' @param tag An number representing the WATLAS tag (either in short format
#' e.g. 4 digits or long format with 11 digits). May be passed as
#' a character or a numeric, and will be converted to a character.
#' For example \code{"31001000001"}.
#' @param tracking_time_start Character representation of time from which
#' start-point data should be retrieved.
#' @param tracking_time_end Character time representing the end point
#' corresponding to the above start point.
#' @param timezone Timezone of tracking_time_start and tracking_time_end.
#'  Must be a valid timezone for the as.POSIXct function.
#' @param database The database name on the host server.
#' @param host The server address on which the data are stored.
#' @param username Username to access the server.
#' @param password Password to access the server.
#' @param SQLiteDB The full path including the filename of a local
#' SQLite-database with tracking data. This argument overrules establishing
#' a connection with the remote host.
#' @param use_connection An R-object with a previously established connection,
#' for instance generated by \code{RMySQL::dbConnect(RMySQL::MySQL(),
#'  user = 'username', password = 'password', dbname = 'database',
#'  host = 'host')}. This argument overrules making a connection to a
#'  local host \code{SQLiteDB} or a remote host.
#' @param chunk_size Number of tags queried per database request (default 50).
#' Tags are split into groups of this size and the results are combined.
#' Reduce this value if fetching large data sets fails with a timeout or
#' "error while fetching rows". Ignored when \code{last_n} is set.
#' @param last_n Optional number of positions to return per tag. If set, only
#' the last \code{last_n} positions of each tag within the selected time
#' window are returned (most recent first in the query, returned in
#' ascending time order). Each tag is then queried separately.
#' Default is \code{NULL}, which returns all positions in the time window.
#' @returns A data.table of positions of the specified tag, filtered between
#' the start and end times.\cr
#' posID	  =	Unique number for positions \cr
#' tag		  =	4 digit tag number (character) \cr
#' time		  =	UNIX time (seconds) \cr
#' datetime = Time stamp in POSIXct (UTC) \cr
#' x		    =	x-coordinates in meters (UTM 31 N) \cr
#' y		    =	y-coordinates in meters (UTM 31 N) \cr
#' nbs		  =	Number of Base Stations (receivers) used in calculating
#' coordinates \cr
#' varx		  =	Variance in estimating x-coordinates \cr
#' vary		  =	Variance in estimating y-coordinates \cr
#' covxy	  =	Co-variance between y- and y-coordinates \cr
#'
#' @examplesIf requireNamespace("readxl", quietly = TRUE)
#' # packages
#' library(data.table)
#'
#' # file path to the metadata
#' fp <- system.file(
#'   "extdata", "tags_watlas_subset.xlsx", package = "tools4watlas"
#' )
#'
#' # load meta data
#' all_tags <- readxl::read_excel(fp, sheet = "tags_watlas_all") |>
#'   data.table()
#'
#' # subset desired tags using data.table
#' # (for example all tags from 2023)
#' tags <- all_tags[year == 2023]$tag
#'
#' # time period for which data should be extracted form the database (in CET)
#' from <- "2023-09-21 00:00:00"
#' to <- "2023-09-25 00:00:00"
#'
#' # establish database connection
#' sqlite_db <- system.file(
#'   "extdata", "watlas_example.SQLite", package = "tools4watlas"
#' )
#' con <- RSQLite::dbConnect(RSQLite::SQLite(), sqlite_db)
#'
#' # load data from database
#' data <- atl_get_data(
#'   tags,
#'   tracking_time_start = from,
#'   tracking_time_end = to,
#'   timezone = "CET",
#'   use_connection = con
#' )
#'
#' # close connection
#' RSQLite::dbDisconnect(con)
#'
#' @export
#'
atl_get_data <- function(tag,
                         tracking_time_start,
                         tracking_time_end,
                         timezone = "CET",
                         database = "some_database",
                         host = "some.host.nl",
                         username = "someuser",
                         password = "somepassword",
                         SQLiteDB = NULL, # nolint
                         use_connection = NULL,
                         chunk_size = 50,
                         last_n = NULL) {
  # global variables
  TIME <- time <- posID <- datetime <- TAG <- NULL # nolint

  # check input
  assertthat::assert_that(
    all(is.numeric(tag) | is.character(tag)),
    msg = "tag provided must be numeric or character"
  )
  assertthat::assert_that(
    all(nchar(as.character(tag)) < 7 | nchar(as.character(tag)) == 11),
    msg = "tag should be either < 7 digits or full 11 digits"
  )
  assertthat::assert_that(
    is.character(tracking_time_start),
    msg = "start tracking time is not a character"
  )
  assertthat::assert_that(
    is.character(tracking_time_end),
    msg = "end tracking time is not a character"
  )
  assertthat::assert_that(
    is.character(timezone),
    msg = "timezone provided must be numeric or character"
  )
  db_params <- list(host = host, username = username, password = password)
  purrr::iwalk(db_params, function(value, name) {
    assertthat::assert_that(
      is.character(value),
      msg = glue::glue("{name} is not a character")
    )
  })

  # process parameters
  tracking_time_start <- as.POSIXct(tracking_time_start, tz = timezone)
  tracking_time_end <- as.POSIXct(tracking_time_end, tz = timezone)
  attributes(tracking_time_start)$tzone <- "UTC"
  attributes(tracking_time_end)$tzone <- "UTC"
  tracking_time_start <- as.numeric(tracking_time_start) * 1000
  tracking_time_end <- as.numeric(tracking_time_end) * 1000

  # if tag is in short format, create long format
  if (any(nchar(as.character(tag)) < 11)) {
    tag <- atl_full_tag_id(tag)
  }
  tag <- unique(tag)

  # make new connection (once) or use existing
  if (is.null(use_connection)) {
    if (is.null(SQLiteDB)) {
      con <- DBI::dbConnect(
        RMariaDB::MariaDB(),
        user = username,
        password = password,
        dbname = database,
        host = host
      )
    } else {
      con <- DBI::dbConnect(RSQLite::SQLite(), SQLiteDB)
    }
    on.exit(DBI::dbDisconnect(con), add = TRUE)
  } else {
    con <- use_connection
  }

  out_cols <- c(
    "posID", "tag", "time", "datetime", "x", "y",
    "nbs", "varx", "vary", "covxy"
  )

  # split tags into queries
  if (is.null(last_n)) {
    # many tags per query
    tag_chunks <- split(tag, ceiling(seq_along(tag) / chunk_size))
    order_limit <- ""
  } else {
    # LIMIT applies to the whole result, so query one tag at a time
    tag_chunks <- as.list(tag)
    order_limit <- paste0(
      "ORDER BY TIME DESC LIMIT ",
      format(as.integer(last_n), scientific = FALSE)
    )
  }

  results <- vector("list", length(tag_chunks))

  for (i in seq_along(tag_chunks)) {
    sql_query <- glue::glue(
      "SELECT TAG, TIME, X, Y, NBS, VARX, VARY, COVXY
       FROM LOCALIZATIONS
       WHERE TAG IN ({glue::glue_collapse(tag_chunks[[i]], sep = ',')})
         AND TIME > {tracking_time_start}
         AND TIME < {tracking_time_end}
       {order_limit}"
    )

    chunk <- tryCatch(
      DBI::dbGetQuery(con, sql_query),
      error = function(e) {
        hint <- if (is.null(last_n)) {
          paste0(
            "The query probably returned too much data for the server ",
            "(timeout or dropped connection). ",
            "Try a smaller chunk_size, e.g. chunk_size = ",
            max(1, floor(chunk_size / 5)), ", or a shorter time window.\n"
          )
        } else {
          "The query for this tag failed (timeout or dropped connection).\n"
        }
        stop(
          "Fetching data failed for chunk ", i, " of ", length(tag_chunks),
          " (", length(tag_chunks[[i]]), " tags, chunk_size = ", chunk_size,
          ").\n", hint,
          "Original error: ", conditionMessage(e),
          call. = FALSE
        )
      }
    )

    if (nrow(chunk) > 0) {
      data.table::setDT(chunk)
      data.table::setnames(
        chunk,
        old = c("TIME", "X", "Y", "NBS", "VARX", "VARY", "COVXY"),
        new = c("time", "x", "y", "nbs", "varx", "vary", "covxy")
      )
      # milliseconds to seconds, plus a time-stamp in UTC
      chunk[, time := time / 1000]
      chunk[, datetime := as.POSIXct(time, origin = "1970-01-01", tz = "UTC")]
      chunk[, tag := stringr::str_pad(substr(TAG, 8, 11), 4, pad = "0")]
      data.table::setorder(chunk, tag, time)
      chunk[, posID := seq_len(.N), by = tag]
      results[[i]] <- chunk[, out_cols, with = FALSE]
    }
  }

  # combine chunks
  results <- Filter(Negate(is.null), results)
  if (length(results) > 0) {
    out <- data.table::rbindlist(results)
    data.table::setorder(out, tag, time)
    found <- unique(out$tag)
  } else {
    # empty data.table with the same columns
    out <- data.table::data.table(
      posID = integer(),
      tag = character(),
      time = numeric(),
      datetime = as.POSIXct(character(), tz = "UTC"),
      x = numeric(),
      y = numeric(),
      nbs = integer(),
      varx = numeric(),
      vary = numeric(),
      covxy = numeric()
    )
    found <- character()
  }

  # warn once, listing only the tags without data (capped for readability)
  requested <- stringr::str_pad(substr(tag, 8, 11), 4, pad = "0")
  no_data <- setdiff(requested, found)
  if (length(no_data) > 0) {
    n_show <- min(length(no_data), 50)
    warning(
      "No data available for tag ", toString(no_data[seq_len(n_show)]),
      if (length(no_data) > n_show) {
        paste0(" and ", length(no_data) - n_show, " more")
      },
      " in this time period.\n",
      call. = FALSE
    )
  }

  out
}
